    constructor(currentNpc, height = 150, width = 150, x = 355, y = 220, offsetTop = 0, offsetLeft = 0, offsetRight = 0, offsetBottom = 0) {
        super();
        this.loadImgFromCurrentNpc(currentNpc);
        super.loadImage(this.idleImages[0]);
        this.height = height; // 150
        this.width = width; // 150
        this.x = x; // 355
        this.y = y; // 220
        this.lastFrameTime = 0;
        this.currentAnimation = 'idle';
        this.frameInterval = 1000 / 5;
        this.frameIndex = 0;
        this.isFlipped = true;
        this.isGameCharakter = true;
        this.offset.top = offsetTop;
        this.offset.left = offsetLeft;
        this.offset.right = offsetRight;
        this.offset.bottom = offsetBottom;

    }

    loadImgFromCurrentNpc(currentNpc) {
        this.idleImages = this.allNpcs[currentNpc].idle || [];
        this.hypnoImages = this.allNpcs[currentNpc].hypno || [];
        this.walkImages = this.allNpcs[currentNpc].walk || [];
        this.loveImages = this.allNpcs[currentNpc].love || [];
        this.love2Images = this.allNpcs[currentNpc].love2 || [];
        this.eatImages = this.allNpcs[currentNpc].eat || [];
        this.flyUpImages = this.allNpcs[currentNpc].flyUp || [];
        this.afraidImages = this.allNpcs[currentNpc].afraid || [];
        this.halfSizeFlyImages = this.allNpcs[currentNpc].halfSizeFly || [];
        this.fullSizeFlyImages = this.allNpcs[currentNpc].fullSizeFly || [];
    }

    updateState(state, frameInterval = 1000 / 5) {
        switch (state) {
            case 'idle':
                this.currentAnimation = 'idle';
                this.frameInterval = frameInterval;
                break;
            case 'walk':
                this.currentAnimation = 'walk';
                this.frameInterval = frameInterval;
                break;
            case 'hypno':
                this.currentAnimation = 'hypno';
                this.frameInterval = frameInterval;
                break;
            case 'love':
                this.currentAnimation = 'love';
                this.frameInterval = frameInterval;
                break;
            case 'love2':
                this.currentAnimation = 'love2';
                this.frameInterval = frameInterval;
                break;
            case 'eat':
                this.currentAnimation = 'eat';
                this.frameInterval = frameInterval;
                break;
            case 'flyUp':
                this.currentAnimation = 'flyUp';
                this.frameInterval = frameInterval;
                break;
            case 'afraid':
                this.currentAnimation = 'afraid';
                this.frameInterval = frameInterval;
                break;
            case 'halfSizeFly':
                this.currentAnimation = 'halfSizeFly';
                this.frameInterval = frameInterval;
                break;
            case 'fullSizeFly':
                this.currentAnimation = 'fullSizeFly';
                this.frameInterval = frameInterval;
                break;
        }

    }

    updateAnimation(timestamp) {
        if (!this.lastFrameTime) this.lastFrameTime = timestamp;

        const deltaTime = timestamp - this.lastFrameTime;

        if (deltaTime > this.frameInterval) {
            let images = this.getAnimationImages(this.currentAnimation);

            if (images && images.length > 0) {
                this.img.src = images[this.frameIndex % images.length];
                this.frameIndex++;
                this.lastFrameTime = timestamp;
            }
        }
    }

    getAnimationImages(state) {
        switch (state) {
            case 'idle': return this.idleImages;
            case 'hypno': return this.hypnoImages;
            case 'walk': return this.walkImages;
            case 'love': return this.loveImages;
            case 'love2': return this.loveImages;
            case 'eat': return this.eatImages;
            case 'flyUp': return this.flyUpImages;
            case 'afraid': return this.afraidImages;
            case 'halfSizeFly': return this.halfSizeFlyImages;
            case 'fullSizeFly': return this.fullSizeFlyImages;
        }
    }

